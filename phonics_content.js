function page(value) { return pages[String(value)] || pages['1']; }
function letter(value) { return Object.values(pages).find(item => item.letter === value) || pages['1']; }
function entry(word) {
  const location = Object.values(pages).find(item => item.words.includes(word));
  return location ? { word, page: location.page, letter: location.letter, meaning: location.meanings[word], assetBase: location.assetBase } : null;
}
function warm(value) {
  const config = letter(value);
  if (window.PhonicsAudioPacks?.[config.letter]) return Promise.resolve();
  if (!loads.has(config.letter)) {
    loads.set(config.letter, new Promise((resolve, reject) => {
      const script = document.createElement('script');
      script.src = config.assetBase + 'audio-pack.js?v=1';
      script.onload = resolve;
      script.onerror = () => { loads.delete(config.letter); script.remove(); reject(new Error('录音暂时无法加载，请重试')); };
      document.head.append(script);
    }));
  }
  return loads.get(config.letter);
}
function audioURL(value, clip) {
  const config = letter(value);
  const key = config.letter + '/' + clip;
  const encoded = window.PhonicsAudioPacks?.[config.letter]?.[clip];
  if (!encoded) return config.assetBase + clip;
  if (!urls.has(key)) {
    const bytes = Uint8Array.from(atob(encoded), character => character.charCodeAt(0));
    urls.set(key, URL.createObjectURL(new Blob([bytes], { type: 'audio/mpeg' })));
  }
  return urls.get(key);
}
function pool(value) {
  return Object.values(pages).filter(config => Number(config.page) <= Number(value)).flatMap(config =>
    config.words.map(word => ({ word, item: word, key: 'phonics1:word:' + word, pageAbsIndex: Number(config.page) - 1 })));
}
function axeResults(text, meta, target) {
  if (meta.phonicsVerified) return meta.targetWords;
  const heard = String(text).toLowerCase().match(/[\p{L}]+/gu) || [];
  const matches = target === 'Ay ah axe' && meta.targetStatus === 'checked' && heard.length === 3 &&
    ['a', 'ay'].includes(heard[0]) && ['a', 'ah', 'ae', 'æ'].includes(heard[1]) && ['axe', 'ax', 'x'].includes(heard[2]);
  return matches ? target.split(' ').map(text => ({ text, heardClear: true, basis: 'phonics-transcript-alias' })) : meta.targetWords;
}
